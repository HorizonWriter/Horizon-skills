def list_types():
    """返回所有支持的板块类型列表。"""
    return sorted(TEMPLATES.keys())


def get_template(key):
    """根据板块 key 获取模板元数据。支持别名匹配。"""
    if key in TEMPLATES:
        return TEMPLATES[key]
    # 别名匹配
    aliases = {
        "人物": "角色", "角色卡": "角色",
        "组织档案": "组织", "势力": "组织",
        "种族档案": "种族", "亚人": "种族",
        "技术": "科技", "科技条目": "科技",
        "地点": "地理", "地点条目": "地理",
        "事件纪要": "事件", "大事件": "事件",
        "历史条目": "历史", "年表": "历史",
        "物品条目": "物品", "装备": "物品", "资源": "物品",
        "文化条目": "文化", "社会": "文化",
        "生物图鉴": "生物", "生物条目": "生物",
        "疾病条目": "疾病", "病症": "疾病",
        "军事条目": "军事", "武装": "军事",
        "系统条目": "系统", "技术系统": "系统",
        "概要": "凌日星概要", "星球概要": "凌日星概要",
    }
    mapped = aliases.get(key)
    if mapped and mapped in TEMPLATES:
        return TEMPLATES[mapped]
    return None


def guess_type(name_or_path):
    """根据名称或路径猜测板块类型。"""
    # 先尝试目录名匹配
    for k, t in TEMPLATES.items():
        if t["dir"] in name_or_path:
            return t
    return None
